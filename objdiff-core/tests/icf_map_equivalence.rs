//! ICF (`/OPT:ICF`) map-file equivalence, in the shape cea-decomp feeds it.
//!
//! HCEX.pdb keeps every public the linker folded at the folded body's address:
//! `?PushBack@?$dsVECTOR@K$07@@...` and `?PushBack@?$dsVECTOR@PAVSound@FMOD@@$07@@...`
//! both sit at 0x822EC000. The dtk-split target can only name one of them in a
//! relocation; our compiled candidate names the instantiation its source calls.
//! cea-decomp renders those PDB address groups as a synthetic MSVC map
//! (`tools/pdb/icf_map.py`) and names it in objdiff.json `map_file`.
//!
//! These tests pin, on Xenon-style COFF objects and a map in exactly the
//! line format that tool writes:
//!
//!   1. a `bl` to a folded alias is not charged under name_only / name_check
//!      when the map holds both names, and is charged without the map;
//!   2. names in two DIFFERENT groups stay a charge (no closure through a
//!      shared member, no cross-group leak);
//!   3. the map never pairs symbols: a target function and a base function
//!      that the map declares co-located do not become partners, so the map
//!      can raise a relocation comparison but cannot pick what is compared;
//!   4. a large group (HCEX has one with 1,899 publics) parses into the same
//!      relation without materialising its adjacency.

#![cfg(feature = "ppc")]

use objdiff_core::{diff, obj};
use object::{
    Architecture, BinaryFormat, Endianness, SymbolFlags, SymbolKind, SymbolScope,
    write::{Object as WriteObject, Relocation, StandardSection, Symbol, SymbolSection},
};

/// `li r3,3 ; blr`
const LEAF: [u8; 8] = [0x38, 0x60, 0x00, 0x03, 0x4e, 0x80, 0x00, 0x20];
/// `bl 0 ; blr` (the displacement lives in the relocation)
const CALL: [u8; 8] = [0x48, 0x00, 0x00, 0x01, 0x4e, 0x80, 0x00, 0x20];

const CALLER: &str = "?AddFailNotifyAcceptor@bhpPARAMS@@UAAXK@Z";
/// The target's representative for the fold at 0x822EC000.
const PUSH_SOUND: &str = "?PushBack@?$dsVECTOR@PAVSound@FMOD@@$07@@QAAAAPAVSound@FMOD@@ABQAV23@@Z";
/// The instantiation our source calls; same address in the PDB.
const PUSH_ULONG: &str = "?PushBack@?$dsVECTOR@K$07@@QAAAAKABK@Z";
/// A member of a different fold group (`operator[]` at 0x82767440).
const INDEX_TAG: &str = "??A?$dsVECTOR@PAUTAG_INFO@@$07@@QAAAAPAUTAG_INFO@@H@Z";

/// Lines as `tools/pdb/icf_map.py` renders them, comment header included.
const MAP: &str = "\
; SYNTHETIC ICF map -- generated by tools/pdb/icf_map.py. DO NOT EDIT BY HAND.
 0003:0001c000       ?PushBack@?$dsVECTOR@K$07@@QAAAAKABK@Z 822EC000 f   .text
 0003:0001c000       ?PushBack@?$dsVECTOR@PAVSound@FMOD@@$07@@QAAAAPAVSound@FMOD@@ABQAV23@@Z 822EC000 f   .text
 0003:00467440       ??A?$dsVECTOR@PAUTAG_INFO@@$07@@QAAAAPAUTAG_INFO@@H@Z 82767440 f   .text
 0003:00467440       ??A?$dsVECTOR@VrendSR_LAMP_DATA@@$07@@QAAAAVrendSR_LAMP_DATA@@H@Z 82767440 f   .text
";

/// One object: optional defined leaves (`li r3,3; blr`), then `CALLER`
/// (`bl <callee>; blr`). `callee` is either one of `leaves` or, as in a
/// dtk-split target and in most of our objects, an undefined external.
fn build(leaves: &[&str], callee: &str) -> Vec<u8> {
    let mut obj = WriteObject::new(BinaryFormat::Coff, Architecture::PowerPc, Endianness::Big);
    let text = obj.section_id(StandardSection::Text);
    let mut callee_id = None;
    for &leaf in leaves {
        let off = obj.append_section_data(text, &LEAF, 4);
        let id = obj.add_symbol(Symbol {
            name: leaf.as_bytes().to_vec(),
            value: off,
            size: LEAF.len() as u64,
            kind: SymbolKind::Text,
            scope: SymbolScope::Dynamic,
            weak: false,
            section: SymbolSection::Section(text),
            flags: SymbolFlags::None,
        });
        if leaf == callee {
            callee_id = Some(id);
        }
    }
    let callee_id = callee_id.unwrap_or_else(|| {
        obj.add_symbol(Symbol {
            name: callee.as_bytes().to_vec(),
            value: 0,
            size: 0,
            kind: SymbolKind::Text,
            scope: SymbolScope::Dynamic,
            weak: false,
            section: SymbolSection::Undefined,
            flags: SymbolFlags::None,
        })
    });
    let off = obj.append_section_data(text, &CALL, 4);
    obj.add_symbol(Symbol {
        name: CALLER.as_bytes().to_vec(),
        value: off,
        size: CALL.len() as u64,
        kind: SymbolKind::Text,
        scope: SymbolScope::Dynamic,
        weak: false,
        section: SymbolSection::Section(text),
        flags: SymbolFlags::None,
    });
    obj.add_relocation(text, Relocation {
        offset: off,
        symbol: callee_id,
        addend: 0,
        flags: object::RelocationFlags::Coff { typ: object::pe::IMAGE_REL_PPC_REL24 },
    })
    .expect("add bl relocation");
    obj.write().expect("write object")
}

fn mapping(map: Option<&str>) -> diff::MappingConfig {
    let mut m = diff::MappingConfig::default();
    if let Some(text) = map {
        m.symbol_equivalences = obj::map_file::parse_msvc_map(std::io::Cursor::new(text));
    }
    m
}

struct Outcome {
    /// Match percent of the target `CALLER`.
    caller: f32,
    /// Base partner of each queried target symbol (`None` = unpaired).
    partners: Vec<Option<String>>,
}

fn run(
    target_bytes: &[u8],
    base_bytes: &[u8],
    queried: &[&str],
    relocs: diff::FunctionRelocDiffs,
    map: Option<&str>,
) -> Outcome {
    let config = diff::DiffObjConfig { function_reloc_diffs: relocs, ..Default::default() };
    let target =
        obj::read::parse(target_bytes, &config, diff::DiffSide::Target).expect("parse target");
    let base = obj::read::parse(base_bytes, &config, diff::DiffSide::Base).expect("parse base");
    let result = diff::diff_objs(Some(&target), Some(&base), None, &config, &mapping(map))
        .expect("diff objects");
    let left = result.left.as_ref().expect("target diff present");
    let index = |name: &str| {
        target.symbols.iter().position(|s| s.name == name).expect("target symbol present")
    };
    Outcome {
        caller: left.symbols[index(CALLER)].match_percent.expect("caller scored"),
        partners: queried
            .iter()
            .map(|n| left.symbols[index(n)].target_symbol.map(|r| base.symbols[r].name.clone()))
            .collect(),
    }
}

const NAME_RULERS: [diff::FunctionRelocDiffs; 2] =
    [diff::FunctionRelocDiffs::NameOnly, diff::FunctionRelocDiffs::NameCheck];

#[test]
fn folded_alias_call_matches_with_the_map_and_is_charged_without() {
    let target = build(&[], PUSH_SOUND);
    let base = build(&[], PUSH_ULONG);
    for relocs in NAME_RULERS {
        let with = run(&target, &base, &[], relocs, Some(MAP));
        assert_eq!(with.caller, 100.0, "{relocs:?}: both names are the body at 0x822EC000");
        let without = run(&target, &base, &[], relocs, None);
        assert!(without.caller < 100.0, "{relocs:?}: no map, the name difference is a charge");
    }
}

#[test]
fn folded_alias_call_matches_when_the_callee_is_defined_on_both_sides() {
    // Our object defines the COMDAT it calls; a target unit may hold its
    // representative's body. The comparison is by name either way.
    let target = build(&[PUSH_SOUND], PUSH_SOUND);
    let base = build(&[PUSH_ULONG], PUSH_ULONG);
    for relocs in NAME_RULERS {
        assert_eq!(run(&target, &base, &[], relocs, Some(MAP)).caller, 100.0, "{relocs:?}");
    }
}

#[test]
fn names_in_different_groups_stay_a_charge() {
    let target = build(&[], PUSH_SOUND);
    let base = build(&[], INDEX_TAG);
    for relocs in NAME_RULERS {
        assert!(run(&target, &base, &[], relocs, Some(MAP)).caller < 100.0, "{relocs:?}");
    }
    // A name absent from the map aliases nothing, not even across a group.
    let base = build(&[], "?Unrelated@@YAXXZ");
    for relocs in NAME_RULERS {
        assert!(run(&target, &base, &[], relocs, Some(MAP)).caller < 100.0, "{relocs:?}");
    }
}

#[test]
fn the_map_never_pairs_symbols() {
    // Target defines the representative, base defines the folded alias with
    // identical bytes. They are the same address in the PDB, but pairing is by
    // name only: neither partners the other, with or without the map.
    let target = build(&[PUSH_SOUND], PUSH_SOUND);
    let base = build(&[PUSH_ULONG], PUSH_ULONG);
    for relocs in NAME_RULERS {
        for map in [None, Some(MAP)] {
            let out = run(&target, &base, &[PUSH_SOUND, CALLER], relocs, map);
            assert_eq!(out.partners[0], None, "{relocs:?} map={}", map.is_some());
            assert_eq!(out.partners[1], Some(CALLER.to_string()), "{relocs:?}");
        }
    }
}

#[test]
fn a_large_group_is_one_relation() {
    // HCEX.pdb: 1,899 publics at 0x82719350 (`return false;` virtuals).
    let mut text = String::new();
    for i in 0..1899 {
        text.push_str(&format!(" 0003:00419350       ?F{i}@C{i}@@UAA_NXZ 82719350 f   .text\n"));
    }
    let eq = obj::map_file::parse_msvc_map(std::io::Cursor::new(text));
    assert_eq!(eq.len(), 1899);
    assert_eq!(eq.group_count(), 1);
    assert!(eq.aliases("?F0@C0@@UAA_NXZ", "?F1898@C1898@@UAA_NXZ"));
    assert!(eq.aliases("?F1898@C1898@@UAA_NXZ", "?F0@C0@@UAA_NXZ"));
    assert!(!eq.aliases("?F0@C0@@UAA_NXZ", "?F1899@C1899@@UAA_NXZ"));
    assert_eq!(eq.canonical("?F7@C7@@UAA_NXZ"), "?F0@C0@@UAA_NXZ");
}
