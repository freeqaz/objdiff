use std::collections::{HashMap, HashSet};
use std::io::BufRead;

use regex::Regex;

/// Parse an MSVC linker map file and return ICF equivalence groups.
///
/// Each symbol name maps to the set of all symbol names sharing the same address.
/// Only addresses with multiple symbols (ICF-merged) produce entries.
///
/// A real linker map gives every symbol name exactly one address, so each name
/// lands in exactly one group and the result is a partition. Synthetic maps
/// (rb3-xenon's `icf_aliases.map`, dc3's `icf_aliases.map`) can and do emit the
/// same name at several addresses, because the alias data they render is a
/// many-to-many relation and this file format can only express a partition. For
/// such a name the group assignment is a choice, and it is made here
/// **deterministically: the FIRST address at which the name appears in the file
/// wins.** The previous code iterated a `HashMap` and let the last group
/// encountered win, so the choice was decided by `RandomState`'s per-process
/// seed — the same binary on the same map file could score a function 100% on
/// one run and charge a `[sym]` mismatch on the next.
///
/// First-wins rather than last-wins because these maps are generated by
/// appending groups: with last-wins, appending a group that happens to mention
/// an already-listed name silently re-points that name's group and moves the
/// score of unrelated functions. With first-wins, appending is monotone for
/// every name already in the file.
pub fn parse_msvc_map(reader: impl BufRead) -> HashMap<String, HashSet<String>> {
    let pattern =
        Regex::new(r"^\s*\d{4}:[0-9a-fA-F]+\s+(\S+)\s+([0-9a-fA-F]{8})\s+").expect("invalid regex");

    // `address_order` keeps first-seen line order; `address_to_symbols` is only
    // the lookup. Iterating the HashMap directly is what made this parser
    // nondeterministic.
    let mut address_order: Vec<String> = Vec::new();
    let mut address_to_symbols: HashMap<String, Vec<String>> = HashMap::new();

    for line in reader.lines() {
        let Ok(line) = line else { continue };
        if let Some(caps) = pattern.captures(&line) {
            let symbol = caps[1].to_string();
            let address = caps[2].to_uppercase();
            match address_to_symbols.entry(address.clone()) {
                std::collections::hash_map::Entry::Occupied(mut e) => e.get_mut().push(symbol),
                std::collections::hash_map::Entry::Vacant(e) => {
                    address_order.push(address);
                    e.insert(vec![symbol]);
                }
            }
        }
    }

    // Build equivalence map: only for addresses with multiple symbols. Addresses
    // are visited in first-seen order and a name already assigned keeps its
    // group, so the result depends only on the file contents.
    let mut equivalences: HashMap<String, HashSet<String>> = HashMap::new();
    for address in &address_order {
        let symbols = &address_to_symbols[address];
        if symbols.len() > 1 {
            let group: HashSet<String> = symbols.iter().cloned().collect();
            for sym in symbols {
                equivalences.entry(sym.clone()).or_insert_with(|| group.clone());
            }
        }
    }
    equivalences
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Cursor;

    #[test]
    fn test_parse_msvc_map_icf() {
        let map_content = "\
 0005:00001360       ??_GObjRef@@UAAPAXI@Z      82331360 f i App.obj
 0005:00001360       ??_EObjRef@@UAAPAXI@Z      82331360 f i App.obj
 0005:00002000       ?Foo@@YAXXZ                82332000 f   App.obj
 0005:00003000       ?Bar@@YAXXZ                82333000 f   App.obj
";
        let reader = Cursor::new(map_content);
        let equivalences = parse_msvc_map(reader);

        // The two symbols at 82331360 should be equivalent
        assert!(equivalences.contains_key("??_GObjRef@@UAAPAXI@Z"));
        assert!(equivalences.contains_key("??_EObjRef@@UAAPAXI@Z"));
        let group = &equivalences["??_GObjRef@@UAAPAXI@Z"];
        assert!(group.contains("??_EObjRef@@UAAPAXI@Z"));
        assert!(group.contains("??_GObjRef@@UAAPAXI@Z"));
        assert_eq!(group.len(), 2);

        // Unique symbols should not be in the map
        assert!(!equivalences.contains_key("?Foo@@YAXXZ"));
        assert!(!equivalences.contains_key("?Bar@@YAXXZ"));
    }

    #[test]
    fn test_parse_msvc_map_empty() {
        let reader = Cursor::new("");
        let equivalences = parse_msvc_map(reader);
        assert!(equivalences.is_empty());
    }

    /// A name at two addresses is a choice, and the choice must not depend on
    /// `HashMap` iteration order. Before the first-wins fix this assertion failed
    /// on roughly half of runs of the SAME binary: `?Dup@@YAXXZ` was assigned
    /// whichever of the two groups the random iteration order visited last.
    ///
    /// Run it many times in one process to make the old failure deterministic —
    /// each `parse_msvc_map` call builds fresh `HashMap`s with fresh seeds.
    #[test]
    fn test_parse_msvc_map_duplicate_address_is_first_wins() {
        let map_content = "\
 0005:00001360       ?Dup@@YAXXZ                82331360 f i App.obj
 0005:00001360       ?First@@YAXXZ              82331360 f i App.obj
 0005:00002000       ?Dup@@YAXXZ                82332000 f i App.obj
 0005:00002000       ?Second@@YAXXZ             82332000 f i App.obj
";
        for _ in 0..256 {
            let equivalences = parse_msvc_map(Cursor::new(map_content));
            let group = &equivalences["?Dup@@YAXXZ"];
            // The first address wins, every time.
            assert!(group.contains("?First@@YAXXZ"), "first-seen group must win");
            assert!(!group.contains("?Second@@YAXXZ"), "later group must not overwrite");
            assert_eq!(group.len(), 2);
            // The names that are NOT duplicated are unaffected either way.
            assert!(equivalences["?First@@YAXXZ"].contains("?Dup@@YAXXZ"));
            assert!(equivalences["?Second@@YAXXZ"].contains("?Dup@@YAXXZ"));
        }
    }

    /// The whole map must be reproducible, not just the duplicated name: parsing
    /// the same bytes twice has to give the same equivalences.
    #[test]
    fn test_parse_msvc_map_is_reproducible() {
        let map_content = "\
 0005:00001360       ?A@@YAXXZ                  82331360 f i App.obj
 0005:00001360       ?Shared@@YAXXZ             82331360 f i App.obj
 0005:00002000       ?B@@YAXXZ                  82332000 f i App.obj
 0005:00002000       ?Shared@@YAXXZ             82332000 f i App.obj
 0005:00003000       ?C@@YAXXZ                  82333000 f i App.obj
 0005:00003000       ?Shared@@YAXXZ             82333000 f i App.obj
";
        let first = parse_msvc_map(Cursor::new(map_content));
        for _ in 0..256 {
            assert_eq!(parse_msvc_map(Cursor::new(map_content)), first);
        }
    }

    #[test]
    fn test_parse_msvc_map_three_way_merge() {
        let map_content = "\
 0005:00001360       ?A@@YAXXZ                  82331360 f i App.obj
 0005:00001360       ?B@@YAXXZ                  82331360 f i App.obj
 0005:00001360       ?C@@YAXXZ                  82331360 f i App.obj
";
        let reader = Cursor::new(map_content);
        let equivalences = parse_msvc_map(reader);

        assert_eq!(equivalences.len(), 3);
        let group = &equivalences["?A@@YAXXZ"];
        assert!(group.contains("?B@@YAXXZ"));
        assert!(group.contains("?C@@YAXXZ"));
        assert_eq!(group.len(), 3);
    }
}
